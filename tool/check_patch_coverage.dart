import 'dart:io';

/// Fails when changed production lines are not covered by tests.
///
/// Usage:
/// ```sh
/// dart run tool/check_patch_coverage.dart --base origin/main
/// ```
///
/// The tool intersects the lines added or modified relative to `--base` with
/// line-hit data from lcov files produced by the test suite, and requires
/// every executable changed line to be covered. Changed lines absent from the
/// lcov data count as ignored (comments, blank lines, declarations); a changed
/// production file that no test loaded at all is a failure, because its lines
/// cannot be classified as either.
///
/// Default include patterns cover the packages' libraries, the benchmarks
/// harness, and `tool/` scripts. Paths that the unit-test lanes cannot
/// execute — browser-only sources, generated files, and the FFI runtimes that
/// need the native library — are excluded; the report lists the exclusions so
/// they stay honest.

/// Exit code when the patch is not fully covered.
const int coverageFailureExitCode = 1;

/// Paths whose changes are measured.
const List<String> defaultIncludes = <String>[
  'packages/*/lib/**/*.dart',
  'benchmarks/lib/**/*.dart',
  'tool/**/*.dart',
];

/// Paths whose changes the unit-test lanes cannot execute.
const List<String> defaultExcludes = <String>[
  // Generated by ffigen; exercised through the hand-written wrappers.
  '**/*.g.dart',
  // Browser-only sources: the VM test lanes cannot load them.
  '**/web/**',
  '**/*_web.dart',
  '**/web.dart',
  '**/web_converters.dart',
  '**/platform_web.dart',
  '**/platform_stub.dart',
  '**/runtime_web.dart',
  '**/runtime_stub.dart',
  // Needs the MediaPipe native runtime; covered by the native integration
  // lanes, which do not emit lcov yet.
  '**/runtime_native.dart',
  '**/native/pixel_acceleration.dart',
  // Browser-only accelerator stub selected by a conditional import.
  '**/pixel_acceleration_stub.dart',
  // Executables and examples are not part of the coverage contract.
  '**/bin/**',
  '**/example/**',
  '**/examples/**',
  '**/test/**',
  '**/integration_test/**',
];

/// Glob patterns locating lcov files when none are passed with `--lcov`.
const List<String> defaultLcovPatterns = <String>[
  'coverage/lcov.info',
  'packages/*/coverage/lcov.info',
  'benchmarks/coverage/lcov.info',
];

/// One production file's patch-coverage outcome.
final class FileCoverage {
  /// Creates the outcome for [path].
  const FileCoverage({
    required this.path,
    required this.changedLines,
    required this.uncoveredLines,
    required this.hasCoverageData,
  });

  /// Repository-relative path.
  final String path;

  /// Added or modified line numbers relative to the base commit.
  final Set<int> changedLines;

  /// Changed lines that executed zero times; when the file has no coverage
  /// data at all this holds every changed line.
  final Set<int> uncoveredLines;

  /// Whether any lcov record described this file.
  final bool hasCoverageData;

  /// Whether this file's patch is acceptable.
  bool get isCovered => uncoveredLines.isEmpty && hasCoverageData;
}

/// The patch-coverage outcome for a whole diff.
final class PatchCoverageResult {
  /// Creates a result from per-file outcomes.
  const PatchCoverageResult({required this.files});

  /// One outcome per changed production file, sorted by path.
  final List<FileCoverage> files;

  /// Covered changed lines divided by executable changed lines, in percent.
  double get percent {
    final int changed = files.fold<int>(
      0,
      (int sum, FileCoverage file) => sum + file.changedLines.length,
    );
    final int covered =
        changed -
        files.fold<int>(0, (int sum, FileCoverage file) => sum + file.uncoveredLines.length);

    return changed == 0 ? 100 : covered * 100 / changed;
  }

  /// Whether every changed file is fully covered.
  bool get isComplete => files.every((FileCoverage file) => file.isCovered);
}

/// Parses a unified diff into per-file sets of added or modified line numbers.
///
/// Lines are new-file line numbers; deletions and files removed entirely
/// (`+++ /dev/null`) are ignored.
Map<String, Set<int>> parseAddedLines(String diff) {
  final Map<String, Set<int>> added = <String, Set<int>>{};
  String? path;

  for (final String line in diff.split('\n')) {
    if (line.startsWith('diff --git ')) {
      // A new file header resets the path; `+++ /dev/null` deletions then
      // leave it null so their hunks are skipped.
      path = null;
    } else if (line.startsWith('+++ b/')) {
      path = line.substring(6);
    } else if (line.startsWith('@@')) {
      final RegExpMatch? match = RegExp(r'\+(\d+)(?:,(\d+))?').firstMatch(line);

      if (match == null || path == null) continue;

      final int start = int.parse(match.group(1)!);
      final int count = match.group(2) == null ? 1 : int.parse(match.group(2)!);

      if (count > 0) {
        final Set<int> lines = added.putIfAbsent(path, () => <int>{});

        for (int number = start; number < start + count; number += 1) {
          lines.add(number);
        }
      }
    }
  }

  return added;
}

/// Parses lcov records into per-file line-hit counts.
Map<String, Map<int, int>> parseLcov(String contents) {
  final Map<String, Map<int, int>> hits = <String, Map<int, int>>{};
  String? path;

  for (final String line in contents.split('\n')) {
    if (line.startsWith('SF:')) {
      path = line.substring(3);
    } else if (line.startsWith('DA:')) {
      final List<String> parts = line.substring(3).split(',');
      final int? number = parts.isNotEmpty ? int.tryParse(parts[0]) : null;
      final int? count = parts.length >= 2 ? int.tryParse(parts[1]) : null;

      if (path != null && number != null && count != null) {
        final Map<int, int> fileHits = hits.putIfAbsent(path, () => <int, int>{});

        fileHits[number] = (fileHits[number] ?? 0) + count;
      }
    } else if (line == 'end_of_record') {
      path = null;
    }
  }

  return hits;
}

/// Matches [path] against [pattern].
///
/// `**` matches zero or more whole path segments, `*` stays within one
/// segment, and `?` matches one character — the same shape as `package:glob`
/// without the dependency.
bool globMatch(String pattern, String path) {
  final List<String> segments = pattern.split('/');
  final StringBuffer expression = StringBuffer('^');
  bool pendingSeparator = false;

  for (int index = 0; index < segments.length; index += 1) {
    final String segment = segments[index];

    if (segment == '**') {
      // A `**` segment matches zero or more whole directories: when it is the
      // last segment it eats the remainder, otherwise it collapses together
      // with the separator that follows it.
      if (index == segments.length - 1) {
        if (pendingSeparator) expression.write('/');
        expression.write('.*');
      } else {
        if (pendingSeparator) expression.write('/');
        expression.write('(?:.*/)?');
      }
      pendingSeparator = false;
      continue;
    }

    if (pendingSeparator) expression.write('/');

    for (int position = 0; position < segment.length; position += 1) {
      final String character = segment[position];

      if (character == '*') {
        expression.write('[^/]*');
      } else if (character == '?') {
        expression.write('[^/]');
      } else {
        expression.write(RegExp.escape(character));
      }
    }

    pendingSeparator = true;
  }

  return RegExp('$expression\$').hasMatch(path);
}

/// Resolves an lcov `SF:` path against the repository [root] and the lcov
/// file's package [prefix].
///
/// Returns the repository-relative path, or `null` when the recorded path
/// points outside the repository or matches no existing file.
String? resolveLcovPath(String root, String prefix, String recorded) {
  String candidate;

  if (recorded.startsWith('/') || recorded.contains(r':\')) {
    if (!recorded.startsWith(root)) return null;

    candidate = recorded.substring(root.length);
  } else if (File('$root/$recorded').existsSync()) {
    candidate = recorded;
  } else if (File('$root/$prefix/$recorded').existsSync()) {
    candidate = '$prefix/$recorded';
  } else {
    return null;
  }

  while (candidate.startsWith('/')) {
    candidate = candidate.substring(1);
  }

  return candidate;
}

/// Computes patch coverage for [changed] against merged lcov [hits].
PatchCoverageResult computePatchCoverage({
  required Map<String, Set<int>> changed,
  required Map<String, Map<int, int>> hits,
  required List<String> includes,
  required List<String> excludes,
}) {
  final List<FileCoverage> files = <FileCoverage>[];

  for (final MapEntry<String, Set<int>> entry in changed.entries) {
    final String path = entry.key;

    if (!includes.any((String pattern) => globMatch(pattern, path))) continue;
    if (excludes.any((String pattern) => globMatch(pattern, path))) continue;

    final Map<int, int>? fileHits = hits[path];
    // Lines without an lcov record are not executable (comments, blank lines,
    // declarations) and are ignored; a recorded hit count of zero means a test
    // loaded the file but the line never ran.
    final Set<int> uncovered = fileHits == null
        ? Set<int>.of(entry.value)
        : <int>{
            for (final int line in entry.value)
              if (fileHits.containsKey(line) && fileHits[line] == 0) line,
          };

    files.add(
      FileCoverage(
        path: path,
        changedLines: entry.value,
        uncoveredLines: uncovered,
        hasCoverageData: fileHits != null,
      ),
    );
  }

  files.sort((FileCoverage a, FileCoverage b) => a.path.compareTo(b.path));

  return PatchCoverageResult(files: files);
}

/// Renders the outcome as a Markdown report.
String renderReport(PatchCoverageResult result, double minimum) {
  final StringBuffer buffer = StringBuffer()
    ..writeln('### Patch coverage: ${result.percent.toStringAsFixed(1)}%')
    ..writeln();

  if (result.files.isEmpty) {
    buffer.writeln('No changed production lines to verify.');

    return buffer.toString();
  }

  buffer
    ..writeln('| file | changed | uncovered |')
    ..writeln('| --- | ---: | --- |');

  for (final FileCoverage file in result.files) {
    final String uncovered = !file.hasCoverageData
        ? 'no coverage data'
        : file.uncoveredLines.isEmpty
        ? '—'
        : file.uncoveredLines.toList().join(', ');

    buffer.writeln('| ${file.path} | ${file.changedLines.length} | $uncovered |');
  }

  if (!result.isComplete) {
    buffer
      ..writeln()
      ..writeln(
        'Required minimum is $minimum%. Add or extend tests until every changed production line runs.',
      );
  }

  return buffer.toString();
}

/// Expands a single-`*` glob such as `packages/*/coverage/lcov.info` against
/// the repository root, returning matching files' repository-relative paths.
List<String> expandLcovPattern(String root, String pattern) {
  List<String> prefixes = <String>[''];

  for (final String segment in pattern.split('/')) {
    if (!segment.contains('*')) {
      prefixes = <String>[
        for (final String prefix in prefixes) prefix.isEmpty ? segment : '$prefix/$segment',
      ];
      continue;
    }

    final RegExp matcher = RegExp('^${segment.replaceAll('*', '[^/]*')}\$');
    final List<String> expanded = <String>[];

    for (final String prefix in prefixes) {
      final String parent = prefix.isEmpty ? root : '$root/$prefix';
      final Directory directory = Directory(parent);

      if (!directory.existsSync()) continue;

      for (final FileSystemEntity entity in directory.listSync(followLinks: false)) {
        final String name = entity.uri.pathSegments.where((String s) => s.isNotEmpty).last;

        if (matcher.hasMatch(name)) {
          expanded.add(prefix.isEmpty ? name : '$prefix/$name');
        }
      }
    }

    prefixes = expanded;
  }

  return <String>[
    for (final String path in prefixes)
      if (File('$root/$path').existsSync()) path,
  ];
}

/// Whether a Dart source consists solely of directives and comments.
///
/// Barrel files such as `mp_core.dart` only `export` other libraries. They
/// contain no executable code, so no coverage record is ever written for them;
/// without this check a changed export line would be reported as unmeasured.
bool isDirectiveOnly(String source) {
  // Drop block and line comments, then look at each `;`-terminated statement
  // so directives wrapped across lines by the formatter still count.
  final String code = source
      .replaceAll(RegExp(r'/\*[\s\S]*?\*/'), ' ')
      .replaceAll(RegExp(r'//[^\n]*'), ' ');

  for (final String statement in code.split(';')) {
    final String trimmed = statement.trim();

    if (trimmed.isEmpty) continue;

    final bool isDirective =
        trimmed.startsWith('export ') ||
        trimmed.startsWith('import ') ||
        trimmed.startsWith('library') ||
        trimmed.startsWith('part ') ||
        trimmed.startsWith('@');

    if (!isDirective) return false;
  }

  return true;
}

/// Exit code for invalid command-line usage, matching `EX_USAGE`.
const int usageExitCode = 64;

/// Runs the check for [arguments] against the repository at [root].
///
/// Returns the process exit code instead of exiting so tests can drive it in
/// process; [main] forwards the code to [exitCode].
Future<int> runPatchCoverageCheck(
  List<String> arguments, {
  required String root,
  required StringSink out,
  required StringSink err,
}) async {
  String? base;
  double minimum = 100;
  String? summaryPath;
  final Map<String, String> lcovFiles = <String, String>{};

  try {
    for (int index = 0; index < arguments.length; index += 1) {
      final String argument = arguments[index];

      String value() {
        index += 1;

        if (index >= arguments.length) {
          throw FormatException('Option "$argument" requires a value.');
        }

        return arguments[index];
      }

      switch (argument) {
        case '--base':
          base = value();
        case '--lcov':
          final String lcov = value();
          final int separator = lcov.indexOf('@');

          if (separator == -1) {
            lcovFiles[lcov] = '';
          } else {
            lcovFiles[lcov.substring(0, separator)] = lcov.substring(separator + 1);
          }
        case '--min':
          minimum = switch (num.tryParse(value())) {
            final num parsed when parsed >= 0 && parsed <= 100 => parsed.toDouble(),
            _ => throw const FormatException(
              'Option "--min" requires a percentage between 0 and 100.',
            ),
          };
        case '--summary':
          summaryPath = value();
        default:
          throw FormatException('Unknown option "$argument".');
      }
    }

    if (base == null) {
      throw const FormatException(
        '--base is required; pass the merge-base ref, for example origin/main.',
      );
    }
  } on FormatException catch (error) {
    err.writeln(error.message);

    return usageExitCode;
  }

  final String diffText;

  try {
    final String ancestor = (await _git(root, <String>['merge-base', base, 'HEAD'])).trim();

    diffText = await _git(root, <String>[
      'diff',
      '--unified=0',
      '--no-color',
      '--no-ext-diff',
      ancestor,
      'HEAD',
    ]);
  } on ProcessException catch (error) {
    err.writeln('git ${error.arguments.join(' ')} failed: ${error.message}');

    return coverageFailureExitCode;
  }

  for (final String pattern in defaultLcovPatterns) {
    for (final String path in expandLcovPattern(root, pattern)) {
      lcovFiles.putIfAbsent(path, () {
        // The prefix is the package root: two levels above `<pkg>/coverage/lcov.info`.
        final List<String> segments = path.split('/');

        segments.removeLast();
        segments.removeLast();

        return segments.join('/');
      });
    }
  }

  if (lcovFiles.isEmpty) {
    err.writeln('No lcov files found; run the test suite with coverage first.');

    return coverageFailureExitCode;
  }

  out.writeln('Reading ${lcovFiles.length} lcov file(s).');

  final Map<String, Map<int, int>> hits = <String, Map<int, int>>{};

  for (final MapEntry<String, String> entry in lcovFiles.entries) {
    final File file = File(entry.key.startsWith('/') ? entry.key : '$root/${entry.key}');

    if (!file.existsSync()) continue;

    for (final MapEntry<String, Map<int, int>> record in parseLcov(
      file.readAsStringSync(),
    ).entries) {
      final String? resolved = resolveLcovPath(root, entry.value, record.key);

      if (resolved == null) {
        err.writeln('Skipping unresolvable lcov path "${record.key}" from ${entry.key}.');

        continue;
      }

      final Map<int, int> merged = hits.putIfAbsent(resolved, () => <int, int>{});

      for (final MapEntry<int, int> line in record.value.entries) {
        merged[line.key] = (merged[line.key] ?? 0) + line.value;
      }
    }
  }

  final Map<String, Set<int>> changed = parseAddedLines(diffText);

  for (final String path in changed.keys) {
    final File source = File('$root/$path');

    if (!hits.containsKey(path) &&
        path.endsWith('.dart') &&
        source.existsSync() &&
        isDirectiveOnly(source.readAsStringSync())) {
      // Loaded-but-empty is how an executable-free file would look in lcov.
      hits[path] = <int, int>{};
    }
  }

  final PatchCoverageResult result = computePatchCoverage(
    changed: changed,
    hits: hits,
    includes: defaultIncludes,
    excludes: defaultExcludes,
  );
  final String report = renderReport(result, minimum);

  out.writeln(report);

  if (summaryPath case final String summary) {
    final IOSink sink = File(
      summary.startsWith('/') ? summary : '$root/$summary',
    ).openWrite(mode: FileMode.append);

    sink.writeln(report);
    await sink.flush();
    await sink.close();
  }

  return result.percent < minimum || !result.isComplete ? coverageFailureExitCode : 0;
}

/// Runs `git` with [arguments] in [root], returning stdout or throwing a
/// [ProcessException] carrying stderr when the command fails.
Future<String> _git(String root, List<String> arguments) async {
  final ProcessResult result = await Process.run('git', arguments, workingDirectory: root);

  if (result.exitCode != 0) {
    throw ProcessException('git', arguments, (result.stderr as String).trim(), result.exitCode);
  }

  return result.stdout as String;
}

/// Command-line entry point; see the doc comment at the top of this file.
Future<void> main(List<String> arguments) async {
  exitCode = await runPatchCoverageCheck(
    arguments,
    root: Directory.current.path,
    out: stdout,
    err: stderr,
  );
}
